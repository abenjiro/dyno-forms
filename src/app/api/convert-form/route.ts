/**
 * Normalizes and validates an AST schema returned from AI or heuristic generator
 */
function normalizeSchema(schema: any): FormSchema {
  const formId = schema.id || `form_${Date.now()}`;
  const title = schema.title || 'Converted Form';
  const description = schema.description || 'Digitized form generated by Dyno Forms AI.';

  let rootNode = schema.root;
  if (!rootNode || rootNode.type !== 'canvas') {
    rootNode = {
      id: 'root_canvas',
      type: 'canvas',
      isContainer: true,
      children: Array.isArray(schema.children) ? schema.children : [],
    };
  }

  // Ensure recursive node integrity
  function sanitizeNode(node: any, depth = 0): FormNode {
    const nodeId = node.id || `node_${Math.random().toString(36).substring(2, 7)}`;
    const isContainer = Boolean(
      node.isContainer || ['canvas', 'section', 'grid', 'column', 'card', 'tabs'].includes(node.type)
    );

    if (isContainer) {
      return {
        id: nodeId,
        type: node.type || 'section',
        label: node.label || 'Section',
        description: node.description,
        isContainer: true,
        treeDepth: depth,
        layoutProps: node.layoutProps || { columns: node.type === 'grid' ? 2 : 1 },
        children: Array.isArray(node.children)
          ? node.children.map((child: any) => sanitizeNode(child, depth + 1))
          : [],
      };
    }

    const fieldName = node.name || `field_${nodeId}`;
    return {
      id: nodeId,
      type: node.type || 'text',
      name: fieldName,
      label: node.label || 'Input Field',
      description: node.description,
      placeholder: node.placeholder,
      helperText: node.helperText,
      treeDepth: depth,
      validation: node.validation || { required: false },
      dataSource: node.dataSource,
      fieldProps: node.fieldProps,
    };
  }

  const sanitizedRoot = sanitizeNode(rootNode, 0) as any;
  sanitizedRoot.type = 'canvas';
  sanitizedRoot.isContainer = true;

  return {
    id: formId,
    version: '1.0.0',
    title,
    description,
    settings: {
      submitLabel: schema.settings?.submitLabel || 'Submit Form',
      resetLabel: schema.settings?.resetLabel || 'Clear Form',
      showReset: schema.settings?.showReset ?? true,
      enableDrafts: schema.settings?.enableDrafts ?? true,
      submitUrl: schema.settings?.submitUrl || '/api/forms/submit',
      layoutMode: schema.settings?.layoutMode || 'single-page',
    },
    root: sanitizedRoot,
  };
}

